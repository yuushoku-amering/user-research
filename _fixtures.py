def _write(rel, text):
    """写一个 UTF-8 文本素材（不带 BOM，和手写的保持一致）。"""
    p = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    return p


def _write_csv(rel, header, rows):
    """写一个 CSV。**每一格都按 CSV 规矩转义**（里面有逗号/引号/换行也不会炸）。"""
    import csv
    p = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(header)
        for r in rows:
            w.writerow(r)
    return p


def fixture_dir(name):
    """要哪一份素材就造哪一份，返回路径。已经造过就直接给。"""
    builders = {
        "访谈样例": _interview_single,
        "分析样例": _analysis_sample,
        "情景_游戏DAU": _scenario_game_dau,
    }
    if name not in builders:
        raise KeyError("没有这份素材：%s（有：%s）" % (name, "、".join(builders)))
    d = os.path.join(ROOT, name)
    stamp = os.path.join(d, ".built")
    if not os.path.exists(stamp):
        builders[name]()
        with open(stamp, "w", encoding="utf-8") as f:
            f.write("generated by _fixtures.py\n")
    return d


