"""回归测试用的素材 —— **全部现场造，一个字节都不进版本库**。

## 为什么要这样

原来素材是**提交进仓库的文件**（`_fixtures/`）。两个问题：

1. 里面有**故意带手机号、学号、真名的转写稿**（🔒 去标识化那一棒就是要拿它们当靶子）。
   哪怕全是编的，一份公开仓库里躺着「看着像真访谈记录」的文件也不合适 ——
   别人不会知道那是假的。
2. 素材一旦进了库，就变成"不知道谁在什么时候手改过"的东西，
   而它其实**本来就能算出来**（固定随机种子，谁跑都一样）。

所以：**素材的定义搬到这个 .py 里，`_fixtures/` 整个不进库（见 .gitignore）**。
谁要跑测试，这些文件会被现造到 `_jobs/` 下面（`_jobs/` 也不进库）。
仓库里永远只有"怎么造"，没有"造出来的东西"。

## 里面的内容都是编的

产品名「星图扫描」「网游 A」是虚构的；人名、手机号、邮箱、学号、公司、地址
全部是**一眼可见的假数据**（`138-0000-0000` 这种格式、`example.com` 邮箱）。
它们的存在意义只有一个：让去标识化有东西可脱。

## 用法

    from _fixtures import fixture_dir
    d = fixture_dir("访谈样例")        # 需要就现场造，返回目录路径
"""
